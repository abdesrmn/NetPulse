def in_morocco(lat: float, lon: float) -> bool:
    inside = False
    j = len(MOROCCO) - 1
    for i in range(len(MOROCCO)):
        xi, yi = MOROCCO[i]
        xj, yj = MOROCCO[j]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def snap(v: float) -> float:
    return round(math.floor(v / GRID) * GRID + GRID / 2, 4)